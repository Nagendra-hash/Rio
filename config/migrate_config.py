#!/usr/bin/env python3
"""
config/migrate_config.py — One-time migration from config/api_keys.json to config/.env

Run once after upgrading to Pydantic Settings:
    python -m config.migrate_config

This reads the old JSON config, converts to .env format, and validates with
config_doctor(). The old api_keys.json is backed up, not deleted.
"""
from __future__ import annotations

import json
import os
import shutil
from pathlib import Path

# Import our new settings
from config.settings import (
    get_settings, reload_settings, config_doctor, ENV_FILE, BASE_DIR, CONFIG_DIR
)

OLD_CONFIG = CONFIG_DIR / "api_keys.json"
BACKUP_CONFIG = CONFIG_DIR / "api_keys.json.backup"


def migrate() -> dict:
    """Migrate from api_keys.json to .env format."""
    if not OLD_CONFIG.exists():
        return {"ok": True, "message": "No api_keys.json found — nothing to migrate"}

    # Backup first
    shutil.copy2(OLD_CONFIG, BACKUP_CONFIG)
    print(f"Backed up {OLD_CONFIG} → {BACKUP_CONFIG}")

    # Load old config
    with open(OLD_CONFIG, "r", encoding="utf-8") as f:
        old = json.load(f)

    # Build .env lines
    lines = [
        "# JARVIS Configuration — migrated from api_keys.json",
        "# Generated by config/migrate_config.py",
        "",
    ]

    # Environment
    lines.append("# Environment")
    lines.append("JARVIS_ENV=development")
    lines.append("JARVIS_LOG_LEVEL=INFO")
    lines.append("")

    # LLM Providers
    lines.append("# LLM Providers")

    # Gemini
    gemini_keys = old.get("gemini_api_keys") or []
    if not gemini_keys and old.get("gemini_api_key"):
        gemini_keys = [old["gemini_api_key"]]
    if gemini_keys:
        lines.append(f"JARVIS_LLM_GEMINI_API_KEYS={','.join(gemini_keys)}")

    # NVIDIA
    if old.get("nvidia_api_key"):
        lines.append(f"JARVIS_LLM_NVIDIA_API_KEY={old['nvidia_api_key']}")
        lines.append("JARVIS_LLM_NVIDIA_ENABLED=true")

    # OpenRouter
    openrouter_keys = old.get("openrouter_keys") or []
    if openrouter_keys:
        lines.append(f"JARVIS_LLM_OPENROUTER_API_KEYS={','.join(openrouter_keys)}")

    # FreeLLMAPI
    if old.get("freellmapi_api_key"):
        lines.append(f"JARVIS_LLM_FREELLM_API_KEY={old['freellmapi_api_key']}")

    # Ollama
    if old.get("ollama_enabled") is not None:
        lines.append(f"JARVIS_LLM_OLLAMA_ENABLED={'true' if old['ollama_enabled'] else 'false'}")
    if old.get("ollama_models"):
        models = old["ollama_models"]
        if isinstance(models, list):
            lines.append(f"JARVIS_LLM_OLLAMA_MODELS={','.join(models)}")
        else:
            lines.append(f"JARVIS_LLM_OLLAMA_MODELS={models}")

    # Router mode (default smart)
    lines.append("JARVIS_LLM_ROUTER_MODE=smart")

    # Live model
    if old.get("live_model"):
        lines.append(f"JARVIS_LLM_LIVE_MODEL={old['live_model']}")

    lines.append("")

    # Database
    lines.append("# Database")
    lines.append("JARVIS_DB_URL=sqlite+aiosqlite:///./memory/jarvis.db")
    lines.append("")

    # UI
    lines.append("# UI / Dashboard / HUD")
    if old.get("assistant_name"):
        lines.append(f"JARVIS_UI_ASSISTANT_NAME={old['assistant_name']}")
    if old.get("user_name"):
        lines.append(f"JARVIS_UI_USER_NAME={old['user_name']}")
    lines.append("JARVIS_UI_VOICE=Kore")
    if old.get("wake_word_enabled") is not None:
        lines.append(f"JARVIS_UI_WAKE_WORD_ENABLED={'true' if old['wake_word_enabled'] else 'false'}")
    if old.get("push_to_talk_enabled") is not None:
        lines.append(f"JARVIS_UI_PUSH_TO_TALK_ENABLED={'true' if old['push_to_talk_enabled'] else 'false'}")
    if old.get("thinking_enabled") is not None:
        lines.append(f"JARVIS_UI_THINKING_ENABLED={'true' if old['thinking_enabled'] else 'false'}")
    lines.append("")

    # Trading
    lines.append("# Trading / Market Desk")
    if old.get("delta_api_key"):
        lines.append(f"JARVIS_TRADING_DELTA_API_KEY={old['delta_api_key']}")
    if old.get("delta_api_secret"):
        lines.append(f"JARVIS_TRADING_DELTA_API_SECRET={old['delta_api_secret']}")
    lines.append("JARVIS_TRADING_DELTA_TESTNET=true")
    lines.append("JARVIS_TRADING_PAPER_ENABLED=true")
    lines.append("JARVIS_TRADING_DATA_PROVIDER=delta")
    lines.append("")

    # Hermes
    lines.append("# Hermes Bridge")
    lines.append("JARVIS_HERMES_ENABLED=false")
    lines.append("")

    # Agent gates
    lines.append("# Agent Gates (all default to true)")
    lines.append("")

    # Dashboard token
    if old.get("dashboard_auth_token"):
        lines.append(f"JARVIS_UI_DASHBOARD_TOKEN={old['dashboard_auth_token']}")

    # News
    if old.get("currents_api_key"):
        lines.append(f"JARVIS_NEWS_CURRENTS_API_KEY={old['currents_api_key']}")
    if old.get("fred_api_key"):
        lines.append(f"JARVIS_NEWS_FRED_API_KEY={old['fred_api_key']}")

    # FRED is for trading data
    if old.get("fred_api_key"):
        lines.append(f"JARVIS_TRADING_FRED_API_KEY={old['fred_api_key']}")

    # Write .env
    content = "\n".join(lines) + "\n"
    ENV_FILE.write_text(content, encoding="utf-8")
    print(f"Written {ENV_FILE}")

    # Reload settings to validate
    reload_settings()
    doctor = config_doctor()

    return {
        "ok": True,
        "message": "Migration complete",
        "backup": str(BACKUP_CONFIG),
        "env_file": str(ENV_FILE),
        "doctor": doctor,
    }


def main():
    result = migrate()
    import json as _json
    print(_json.dumps(result, indent=2, default=str))

    if result.get("doctor", {}).get("issues"):
        print("\n⚠️  Issues found:")
        for issue in result["doctor"]["issues"]:
            print(f"  - {issue}")
    if result.get("doctor", {}).get("warnings"):
        print("\n⚠️  Warnings:")
        for warn in result["doctor"]["warnings"]:
            print(f"  - {warn}")

    if result["doctor"]["ok"]:
        print("\n✅ Configuration validated successfully!")
        print(f"   You can now use: python -m config.settings")
    else:
        print("\n❌ Configuration has issues — check the output above")
        exit(1)


if __name__ == "__main__":
    main()
