#!/usr/bin/env python3
"""
scientific_skill_scan.py — our own static audit of the vendored skill library.

Upstream ships a scan report (`docs/security-report.json`), and it is useful —
but it is generated by their tooling against their policy, and the brief asks
for OUR review before enabling anything. This script is deliberately small and
readable: it greps the skill files for the behaviours that matter to a host,
records file/line/snippet, and combines that with upstream's verdict.

It never executes skill code. Read-only, offline, stdlib only.

Usage:
    python scripts/scientific_skill_scan.py            # write SCIENTIFIC_SKILLS_SECURITY.json
    python scripts/scientific_skill_scan.py --tty      # print the table only
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE))

from core.scientific.config import (  # noqa: E402
    CORE_SKILLS,
    GUARDED_SKILLS,
    SECURITY_PATH,
    SKILLS_ROOT,
    UPSTREAM_COMMIT,
    UPSTREAM_TAG,
    VENDOR_DIR,
)
from core.scientific.skill_index import build_index  # noqa: E402

SCAN_VERSION = 1

# (rule_id, severity, applies_to, description, regex)
RULES: tuple[tuple[str, str, str, str, re.Pattern], ...] = (
    ("NETWORK", "INFO", "code",
     "makes network requests",
     re.compile(r"\b(requests\.(?:get|post|put|delete)|urllib\.request|urlopen|"
                r"httpx\.|http\.client|socket\.|curl\s|wget\s)", re.I)),
    ("ENV_READ", "INFO", "code",
     "reads environment variables",
     re.compile(r"\bos\.environ\b|\bgetenv\s*\(|\bdotenv\b", re.I)),
    ("SUBPROCESS", "LOW", "code",
     "spawns a child process",
     re.compile(r"\bsubprocess\.|\bos\.system\s*\(|\bos\.popen\s*\(|\bpty\.spawn", re.I)),
    ("DYNAMIC_EXEC", "MEDIUM", "code",
     "evaluates or compiles dynamic code",
     re.compile(r"(?<![A-Za-z0-9_.])(?:eval|exec)\s*\(|\bcompile\s*\(", re.I)),
    ("CREDENTIAL_PATH", "MEDIUM", "code",
     "references a credential store or private key path",
     re.compile(r"\.ssh\b|\.aws\b|\.hermes\b|id_rsa|credentials\.json|\b\.env\b", re.I)),
    ("INSTALL_COMMAND", "LOW", "all",
     "documents a package installation",
     re.compile(r"\b(?:pip|uv\s+pip|conda|npm)\s+install\b|\bapt-get\s+install\b", re.I)),
    ("DESTRUCTIVE", "MEDIUM", "code",
     "contains a destructive filesystem command",
     re.compile(r"\brm\s+-rf\b|\bshutil\.rmtree\b|\bos\.remove\s*\(|\bunlink\s*\(", re.I)),
    ("PROMPT_OVERRIDE", "HIGH", "skill_md",
     "text that tries to override host instructions",
     re.compile(r"ignore\s+(?:all\s+)?(?:previous|prior|above)\s+instructions|"
                r"disregard\s+(?:the\s+)?(?:system|previous)|override\s+(?:the\s+)?"
                r"(?:system|host)\s+prompt|exfiltrat", re.I)),
    ("SELF_CITATION_DIRECTIVE", "LOW", "skill_md",
     "instructs the agent to modify user deliverables with a publisher citation",
     re.compile(r"Citing Scientific Agent Skills", re.I)),
)

_CODE_SUFFIXES = {".py", ".sh", ".bash", ".js", ".mjs", ".ts", ".r", ".jl", ".pl"}
_SEVERITY_ORDER = {"SAFE": 0, "INFO": 1, "LOW": 2, "MEDIUM": 3, "HIGH": 4, "CRITICAL": 5}

# Rule ids the upstream maintainers document as systematic false positives on
# "reads its own API key + calls its own documented endpoint" (see
# docs/security-triage.md). A CRITICAL made only of these is not a reason to
# drop a skill — but it IS a reason to never execute its bundled scripts, which
# is exactly what this integration does.
_KNOWN_FP_RULES = frozenset({
    "BEHAVIOR_ENV_VAR_EXFILTRATION",
    "BEHAVIOR_CROSSFILE_ENV_VAR_EXFILTRATION",
    "BEHAVIOR_CROSSFILE_EXFILTRATION_CHAIN",
    "LLM_SOCIAL_ENGINEERING",
})


def _files(skill_dir: Path):
    code, docs = [], []
    for path in skill_dir.rglob("*"):
        if not path.is_file():
            continue
        if path.suffix.lower() in _CODE_SUFFIXES:
            code.append(path)
        elif path.suffix.lower() in (".md", ".txt", ".yaml", ".yml", ".json"):
            docs.append(path)
    return code, docs


def scan_skill(name: str, skill_dir: Path) -> list[dict]:
    findings: list[dict] = []
    code, docs = _files(skill_dir)
    targets = [(p, "code") for p in code] + [(p, "all") for p in docs]
    targets += [(skill_dir / "SKILL.md", "skill_md")]

    for path, kind in targets:
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if not text.strip():
            continue
        lines = text.splitlines()
        for rule_id, severity, applies, description, pattern in RULES:
            if applies not in (kind, "all"):
                continue
            for number, line in enumerate(lines, 1):
                match = pattern.search(line)
                if not match:
                    continue
                findings.append({
                    "rule_id": rule_id,
                    "severity": severity,
                    "description": description,
                    "file": str(path.relative_to(skill_dir)),
                    "line": number,
                    "snippet": line.strip()[:140],
                })
                break  # one hit per rule per file is enough for triage
    return findings


def max_severity(findings: list[dict]) -> str:
    if not findings:
        return "SAFE"
    return max(findings, key=lambda f: _SEVERITY_ORDER.get(f["severity"], 0))["severity"]


def load_upstream() -> dict:
    path = VENDOR_DIR / "docs" / "security-report.json"
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def upstream_summary(raw: dict) -> dict:
    by_name = {entry.get("name"): entry for entry in raw.get("skills") or []}
    out: dict[str, dict] = {}
    for name in CORE_SKILLS:
        entry = by_name.get(name)
        if not entry:
            out[name] = {"scanned": False}
            continue
        sev: dict[str, int] = {}
        for finding in entry.get("findings") or []:
            key = str(finding.get("severity") or "?").upper()
            sev[key] = sev.get(key, 0) + 1
        out[name] = {
            "scanned": True,
            "is_safe": entry.get("is_safe"),
            "max_severity": entry.get("max_severity"),
            "last_scanned": entry.get("last_scanned"),
            "findings": len(entry.get("findings") or []),
            "severities": sev,
            "findings_detail": [
                {"rule_id": f.get("rule_id"), "severity": f.get("severity")}
                for f in (entry.get("findings") or [])
            ],
        }
    return out


def decisions(our: dict[str, list[dict]], upstream: dict[str, dict]) -> dict[str, dict]:
    """Enable a core skill unless OUR scan or the upstream verdict says HIGH+."""
    result: dict[str, dict] = {}
    for name in CORE_SKILLS:
        mine = our.get(name) or []
        our_max = max_severity(mine)
        up = upstream.get(name) or {}
        up_max = str(up.get("max_severity") or "SAFE").upper()
        ours_high = _SEVERITY_ORDER.get(our_max, 0) >= _SEVERITY_ORDER["HIGH"]
        upstream_high = _SEVERITY_ORDER.get(up_max, 0) >= _SEVERITY_ORDER["HIGH"]
        up_rules = {
            str(f.get("rule_id"))
            for f in (up.get("findings_detail") or [])
            if str(f.get("severity")).upper() in ("CRITICAL", "HIGH")
        }
        false_positive_only = bool(up_rules) and up_rules <= _KNOWN_FP_RULES

        if name in GUARDED_SKILLS:
            verdict, reason = "disabled", GUARDED_SKILLS[name]
        elif ours_high:
            verdict, reason = "disabled", f"our scan found {our_max}"
        elif upstream_high and not false_positive_only:
            verdict, reason = "disabled", (
                f"upstream found {up_max} outside the documented false positives "
                f"({', '.join(sorted(up_rules))})"
            )
        elif upstream_high:
            verdict = "enabled"
            reason = (
                f"upstream {up_max} is limited to documented false-positive rules "
                f"({', '.join(sorted(up_rules))}: env-read + own documented "
                "endpoint). Bundled scripts are never executed; the self-citation "
                "directive is stripped on load."
            )
        else:
            verdict, reason = "enabled", "reviewed: no HIGH+ finding in our scan or upstream's"
        result[name] = {
            "decision": verdict,
            "reason": reason,
            "our_max": our_max,
            "upstream_max": up_max,
            "upstream_high_rules": sorted(up_rules),
        }
    return result


def main() -> int:
    ap = argparse.ArgumentParser(description="Static audit of vendored science skills")
    ap.add_argument("--tty", action="store_true", help="print the table, write nothing")
    args = ap.parse_args()

    index = build_index()
    our: dict[str, list[dict]] = {}
    for name, skill in index.skills.items():
        our[name] = scan_skill(name, Path(skill.path))

    raw_upstream = load_upstream()
    up_core = upstream_summary(raw_upstream)
    verdicts = decisions(our, up_core)

    totals = {"skills_scanned": len(our), "findings": sum(len(v) for v in our.values())}
    by_sev: dict[str, int] = {}
    for findings in our.values():
        for finding in findings:
            by_sev[finding["severity"]] = by_sev.get(finding["severity"], 0) + 1
    totals["by_severity"] = by_sev

    payload = {
        "version": SCAN_VERSION,
        "scanned_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "source": {"tag": UPSTREAM_TAG, "commit": UPSTREAM_COMMIT},
        "rules": [
            {"id": rid, "severity": sev, "applies_to": applies, "description": desc}
            for rid, sev, applies, desc, _ in RULES
        ],
        "our_scan": {"totals": totals,
                     "skills": {name: f for name, f in sorted(our.items()) if f}},
        "upstream_scan": {
            "totals": (raw_upstream.get("totals") or {}),
            "generated": raw_upstream.get("generated"),
            "core_skills": up_core,
        },
        "decisions": verdicts,
        "notes": [
            "We never execute a bundled skill script. Skill files are reference "
            "material; analysis runs use RIO's own vetted recipes and database "
            "clients.",
            "Upstream's BEHAVIOR_*EXFILTRATION CRITICALs are documented by the "
            "maintainers as the 'reads its own API key + calls its own documented "
            "endpoint' pattern (docs/security-triage.md).",
            "The 'Citing Scientific Agent Skills' directive is stripped when a "
            "skill body is loaded, so a skill cannot mutate user deliverables.",
        ],
    }

    print("Scientific skill audit")
    print(f"  skills scanned : {totals['skills_scanned']}")
    print(f"  findings       : {totals['findings']} {by_sev}")
    enabled = [n for n, v in verdicts.items() if v["decision"] == "enabled"]
    disabled = [n for n, v in verdicts.items() if v["decision"] == "disabled"]
    print(f"  core enabled   : {len(enabled)}")
    print(f"  core disabled  : {len(disabled)}")
    for name in disabled:
        print(f"    {name:32} {verdicts[name]['reason']}")

    if args.tty:
        print("\nper-skill (core):")
        for name in CORE_SKILLS:
            mine = our.get(name) or []
            up = up_core.get(name) or {}
            print(f"  {name:32} ours={max_severity(mine):6} "
                  f"upstream={str(up.get('max_severity')):8} files={len(mine)}")
        return 0

    SECURITY_PATH.write_text(json.dumps(payload, indent=1, sort_keys=True), encoding="utf-8")
    print(f"  written        : {SECURITY_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
