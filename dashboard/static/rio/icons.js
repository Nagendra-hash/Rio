/* ── RIOBus — app event bus (real events only) ────────────────────────── */
const RIOBus = (() => {
  const subs = new Map();          // evt -> Set<fn>
  return {
    on(evt, fn) {
      if (!subs.has(evt)) subs.set(evt, new Set());
      subs.get(evt).add(fn);
      return () => subs.get(evt)?.delete(fn);
    },
    emit(evt, data) {
      const set = subs.get(evt);
      if (!set) return;
      for (const fn of set) {
        try { fn(data); } catch (_) { /* a listener must never break the emitter */ }
      }
    },
  };
})();

