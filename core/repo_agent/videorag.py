"""
core/repo_agent/videorag.py — first-party adapter for HKUDS/VideoRAG.

VideoRAG is a repository-style install, so it follows the same contract as
ViMax: the checkout lives at ~/JarvisTools/videorag, `.jarvis/` holds the
adapter manifest + runner wrapper, and the skill is allowlisted in
~/JarvisTools/registry.json.

What is different from a generic install:

* Upstream ships **no packaging metadata** in the algorithm subtree, so the
  environment was provisioned by hand (uv + the pinned 2024 stack) and the
  package installed editable from <repo>/VideoRAG-algorithm. The repo
  manifest therefore carries `env_kind: "uv-manual"`.
* The heavy models (MiniCPM-V int4, faster-distil-whisper, ImageBind) are
  downloaded later, *inside* the checkout, because upstream hardcodes them as
  relative paths. `status` reports exactly which are missing.
* Upstream's visual encoder is loaded with a hardcoded `.cuda()`, so the skill
  is registered as NEEDS_CONFIGURATION until a CUDA device and the three
  checkpoints are present — a false READY would only fail mid-job.

The runner itself stays in Mark-III (`scripts/videorag_run.py`) so there is
one implementation; the wrapper written into the repo just forwards to it.
"""
from __future__ import annotations

import json
import os
import subprocess
from pathlib import Path
from typing import Any

from core.repo_agent import manifests as M

__all__ = ["REPO_NAME", "SKILL_ID", "register", "prepare", "status",
           "skill_definition", "RUNNER"]

REPO_NAME = "videorag"
SKILL_ID = "videorag-chat"

MARK3 = Path("/home/nagendra/Mark-III")
RUNNER = MARK3 / "scripts" / "videorag_run.py"
WORKDIR = MARK3 / "memory" / "videorag"

_WEIGHTS = {
    "MiniCPM-V-2_6-int4": "minicpm_v",
    "faster-distil-whisper-large-v3": "whisper",
    ".checkpoints/imagebind_huge.pth": "imagebind",
}


# ── wrapper written into <repo>/.jarvis/ ────────────────────────────────────
_RUNNER_SOURCE = '''#!/usr/bin/env python
"""JARVIS adapter runner for VideoRAG (generated by core/repo_agent/videorag.py).

Forwards one allowlisted operation to Mark-III's runner
(scripts/videorag_run.py) so the framework keeps a single entry point. The
repo's own venv is the interpreter, and the checkout root is handed over as
VIDEORAG_ROOT because upstream resolves its checkpoints relative to it.
"""
import argparse
import json
import os
import runpy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK3 = Path(os.environ.get("JARVIS_HOME", "/home/nagendra/Mark-III"))
RUNNER = MARK3 / "scripts" / "videorag_run.py"
DEFAULT_WORKDIR = str(MARK3 / "memory" / "videorag")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("op", choices=["ask", "index", "list", "status"])
    ap.add_argument("--params-file")
    args = ap.parse_args()

    params, workdir = {}, DEFAULT_WORKDIR
    if args.params_file:
        payload = json.loads(Path(args.params_file).read_text(encoding="utf-8"))
        params = payload.get("params") or {}
        workdir = str(payload.get("workdir") or DEFAULT_WORKDIR)

    argv = [str(RUNNER), "--workdir", workdir]
    if args.op == "ask":
        argv += ["query", str(params.get("question") or "")]
    elif args.op == "index":
        argv += ["index", str(params.get("path") or "")]
    else:
        argv.append(args.op)

    os.environ["VIDEORAG_ROOT"] = str(ROOT / "VideoRAG-algorithm")
    os.environ["VIDEORAG_PYTHON"] = sys.executable
    os.environ.setdefault("PATH", "/usr/local/bin:/usr/bin:/bin")
    print(f"[VIDEORAG_PROGRESS] {args.op}: starting", flush=True)
    sys.argv = argv
    runpy.run_path(str(RUNNER), run_name="__main__")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


# ── readiness ───────────────────────────────────────────────────────────────
def status(dest: Path | str | None = None) -> dict[str, Any]:
    """GPU + checkpoint readiness, without importing torch."""
    dest = Path(dest) if dest else M.repo_dir(REPO_NAME)
    gpu = False
    try:
        gpu = subprocess.run(["nvidia-smi", "-L"], capture_output=True,
                             timeout=15).returncode == 0
    except Exception:
        gpu = False
    missing = [name for sub, name in _WEIGHTS.items()
               if not (dest / sub).exists()]
    return {"gpu": gpu, "missing_weights": missing,
            "ready": gpu and not missing}


def _skill_status(dest: Path) -> tuple[str, str]:
    st = status(dest)
    if st["ready"]:
        return "READY", "GPU + checkpoints present"
    reasons = []
    if not st["gpu"]:
        reasons.append("no CUDA device")
    if st["missing_weights"]:
        reasons.append("weights missing: " + ", ".join(st["missing_weights"]))
    return "NEEDS_CONFIGURATION", "; ".join(reasons)


# ── registration (called by the manager, or directly) ───────────────────────
def register(dest: Path, repo_manifest: dict[str, Any]) -> dict[str, Any]:
    """Write the adapter manifest + runner wrapper into <repo>/.jarvis/."""
    dest = Path(dest)
    commit = str(repo_manifest.get("commit") or "unknown")
    wrapper = dest / ".jarvis" / "jarvis_run.py"
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    wrapper.write_text(_RUNNER_SOURCE, encoding="utf-8")
    os.chmod(wrapper, 0o755)

    skill = skill_definition(commit)
    M.write_json(M.skill_manifest_path(REPO_NAME), skill)

    state, detail = _skill_status(dest)
    entry = M.upsert_skill({
        "skill_id": SKILL_ID, "repo": REPO_NAME, "name": skill["name"],
        "commit": commit, "enabled": True, "status": state, "detail": detail,
    })
    return {"ok": True, "skill_id": SKILL_ID, "status": entry.get("status"),
            "detail": detail}


def prepare(*, skill_id: str, op: str, params: dict[str, Any],
            run_dir: Path) -> dict[str, Any]:
    """Write the invocation payload the wrapper reads (per-run scratch)."""
    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)
    params_file = run_dir / "params.json"
    payload = {"op": op, "params": dict(params or {}), "workdir": str(WORKDIR)}
    params_file.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return {"params_file": str(params_file)}


